export const DEPARTAMENTOS_PARAGUAY = Object.keys(PARAGUAY_LOCATIONS);

export function getCiudadesPorDepartamento(departamento: string): string[] {
  if (!departamento) return [];
  if (departamento === 'Capital' || departamento === 'Asunción' || departamento.includes('Capital')) {
    return PARAGUAY_LOCATIONS['Asunción (Distrito Capital)'] || ['Asunción'];
  }
  return PARAGUAY_LOCATIONS[departamento] || [];
}
